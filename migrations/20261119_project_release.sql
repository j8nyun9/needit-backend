begin;
alter table public.projects add column if not exists owner_id uuid references auth.users(id);
alter table public.projects add column if not exists deployment_url text;
alter table public.projects add column if not exists release_status text check (release_status in ('기획 중','개발 중','테스트 중','서비스 운영 중'));
update public.projects set release_status=case when status in ('기획 중','개발 중','테스트 중') then status else '개발 중' end where release_status is null;
alter table public.projects alter column release_status set default '개발 중';
alter table public.projects alter column release_status set not null;
alter table public.projects add column if not exists usage_guide text not null default '';
alter table public.projects add column if not exists released_at timestamptz;
create table if not exists public.project_favorites (
 user_id uuid references auth.users(id) on delete cascade,
 project_id bigint references public.projects(id) on delete cascade,
 created_at timestamptz not null default now(), primary key(user_id,project_id)
);
create table if not exists public.project_feedback (
 id bigint generated by default as identity primary key,
 project_id bigint not null references public.projects(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 author_name text not null, kind text not null check(kind in ('review','bug')),
 content text not null check(length(trim(content)) between 1 and 1000),
 created_at timestamptz not null default now()
);
create index if not exists project_feedback_project_created on public.project_feedback(project_id,created_at desc);
create table if not exists public.project_notification_reads (
 user_id uuid references auth.users(id) on delete cascade,
 project_id bigint references public.projects(id) on delete cascade,
 released_at timestamptz not null, primary key(user_id,project_id)
);
alter table public.project_favorites enable row level security;
alter table public.project_feedback enable row level security;
alter table public.project_notification_reads enable row level security;
revoke all on public.project_favorites,public.project_feedback,public.project_notification_reads from anon,authenticated;
grant all on public.project_favorites,public.project_feedback,public.project_notification_reads to service_role;
grant usage,select on sequence public.project_feedback_id_seq to service_role;
revoke update on public.projects from anon,authenticated;
commit;
